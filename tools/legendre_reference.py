"""Independent high-precision reference values for fully normalized Legendre
functions, used by tests/test_legendre_holmes_and_featherstone.cpp.

Each value is computed with mpmath's associated Legendre function legenp
(hypergeometric series, not a recursion) at 50 digits, then normalized:

    Pbar_nm(cos t) = sqrt((2 - delta_m0)(2n+1)(n-m)!/(n+m)!) * (-1)^m * P_n^m(cos t)

The (-1)^m removes the Condon-Shortley phase that mpmath includes, giving the
4-pi geodesy convention of EGM2008. Every value is recomputed at 90 digits and
the script stops if the two disagree beyond 1e-30, so a printed value is
correct to the last of its 17 significant digits.

Usage:  python3 tools/legendre_reference.py > reference.inc
Needs:  pip install mpmath
"""

import sys

import mpmath as mp

# (n, m, colatitude in degrees). Low degrees for sanity, then every regime
# that matters at high degree: near the poles, the equator, high order m,
# values far below 1 (u^m decay), and the southern hemisphere.
POINTS = [
    (0, 0, "37"), (1, 0, "37"), (1, 1, "37"),
    (3, 1, "60"), (3, 2, "60"), (3, 3, "60"),
    (10, 5, "37.3"), (50, 25, "12.5"),
    (100, 0, "1"), (100, 50, "45"), (100, 100, "89.9"),
    (360, 1, "0.1"), (360, 180, "89.5"),
    (1000, 1, "0.5"), (1000, 500, "30"), (1000, 999, "85"),
    (2190, 0, "30"), (2190, 1, "0.25"), (2190, 100, "2"),
    (2190, 1000, "60"), (2190, 1500, "120"), (2190, 2000, "89"),
    (2190, 2188, "90"), (2190, 2190, "80"),
]


def pbar(n: int, m: int, theta_deg: str, dps: int) -> mp.mpf:
    with mp.workdps(dps):
        x = mp.cos(mp.radians(mp.mpf(theta_deg)))
        norm = mp.sqrt((2 if m else 1) * (2 * n + 1) * mp.factorial(n - m) / mp.factorial(n + m))
        return norm * (-1) ** m * mp.legenp(n, m, x)


# Tiny values, deep in the decaying part of a column, where the hypergeometric
# series above does not converge. These come from the same column recursion
# run at 60 digits instead: mpmath numbers have no exponent limit, so no
# scaling is involved, and the rounding error is ~1e-55. They test that the
# C++ unscaling step keeps full precision far below 1e-100.
# (m, colatitude in degrees, [n, ...])
TINY_POINTS = [
    (1285, "20", [1285, 1700, 2190]),
    (600, "5", [600, 1500, 2190]),
    (2600, "45", [2600, 2700]),
]


def pbar_by_recursion(m: int, theta_deg: str, n_wanted, dps: int):
    with mp.workdps(dps):
        th = mp.radians(mp.mpf(theta_deg))
        t, u = mp.cos(th), mp.sin(th)
        p = mp.mpf(1)
        for k in range(1, m + 1):
            p *= u * (mp.sqrt(3) if k == 1 else mp.sqrt(mp.mpf(2 * k + 1) / (2 * k)))
        out = {m: p}
        p2, p1 = mp.mpf(0), p
        for n in range(m + 1, max(n_wanted) + 1):
            a = mp.sqrt(mp.mpf((2 * n - 1) * (2 * n + 1)) / ((n - m) * (n + m)))
            b = (mp.sqrt(mp.mpf((2 * n + 1) * (n + m - 1) * (n - m - 1)) / ((n - m) * (n + m) * (2 * n - 3)))
                 if n > m + 1 else 0)
            p = a * t * p1 - b * p2
            out[n] = p
            p2, p1 = p1, p
        return [out[n] for n in n_wanted]


def main() -> int:
    print("// Generated by tools/legendre_reference.py (mpmath legenp, 50 digits,")
    print("// checked at 90). {n, m, colatitude_deg, Pbar_nm}")
    for n, m, th in POINTS:
        lo = pbar(n, m, th, 50)
        hi = pbar(n, m, th, 90)
        rel = abs(lo - hi) / abs(hi) if hi != 0 else abs(lo - hi)
        if rel > mp.mpf("1e-30"):
            print(f"precision check failed for ({n},{m},{th}): {rel}", file=sys.stderr)
            return 1
        print(f"    {{{n}, {m}, {th}, {float(hi)!r}}},")

    print("// Tiny values: column recursion at 60 digits, checked at 90.")
    print("// {n, m, colatitude_deg, Pbar_nm}")
    for m, th, ns in TINY_POINTS:
        lo = pbar_by_recursion(m, th, ns, 60)
        hi = pbar_by_recursion(m, th, ns, 90)
        for n, a, b in zip(ns, lo, hi):
            if abs(a - b) / abs(b) > mp.mpf("1e-30"):
                print(f"precision check failed for ({n},{m},{th})", file=sys.stderr)
                return 1
            print(f"    {{{n}, {m}, {th}, {mp.nstr(b, 17, min_fixed=1, max_fixed=0)}}},")
    return 0


if __name__ == "__main__":
    sys.exit(main())
